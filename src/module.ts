import { defineNuxtModule, createResolver, addServerHandler, addServerPlugin, addTypeTemplate, addImports, addPlugin } from '@nuxt/kit'
import { defu } from 'defu'

export interface ModuleOptions {
  /** Unleash client API URL. GitLab: Deploy > Feature flags > Configure > API URL. */
  url: string
  /** GitLab: Instance ID. Server-only: it authorizes reading the flags. */
  instanceId: string
  /** GitLab: the environment the app runs in — flag strategies are scoped to environments by this name. */
  appName: string
  /** Seconds between refreshes of the flag definitions on the server. */
  refreshInterval: number
  /** Seconds a page render waits for the first definitions after the server starts; after that the flags are off. */
  readyTimeout: number
  /** Path segment of the endpoint the browser reads flags from: `/api/<customApiPath>/features`. */
  customApiPath: string
}

// Types only: the module entry is build-time code, and a class exported from here would be a different copy from the
// one the `unleash:error` hook receives at runtime.
export type { UnleashContext, FeatureFlagsEvaluation, FeatureFlagsUnavailable } from './runtime/types'

// TypeScript cannot infer the return type without referencing internal Nuxt types
// This is a known limitation when generating declaration files for Nuxt modules
const moduleDefinition = defineNuxtModule<ModuleOptions>({
  meta: {
    name: 'approck-nuxt-unleash',
    configKey: 'unleash',
  },
  defaults: {
    url: '',
    instanceId: '',
    appName: '',
    refreshInterval: 15,
    readyTimeout: 5,
    customApiPath: 'unleash',
  },
  setup(options, nuxt) {
    const { resolve } = createResolver(import.meta.url)

    // Server-only settings, overridable at runtime with NUXT_UNLEASH_URL, NUXT_UNLEASH_INSTANCE_ID, NUXT_UNLEASH_APP_NAME…
    const { customApiPath, ...serverOptions } = options
    nuxt.options.runtimeConfig.unleash = defu(
      nuxt.options.runtimeConfig.unleash as Partial<typeof serverOptions> | undefined,
      serverOptions,
    )
    const apiPath = `/api/${customApiPath}/features`
    nuxt.options.runtimeConfig.public.unleash = defu(
      nuxt.options.runtimeConfig.public.unleash as { apiPath?: string } | undefined,
      { apiPath },
    )

    addServerPlugin(resolve('./runtime/server/plugin'))
    addServerHandler({
      route: apiPath,
      method: 'post',
      handler: resolve('./runtime/server/api/features.post'),
    })

    // Runs after the app's plugins (`enforce: 'post'`): the app writes the evaluation context before it is read.
    addPlugin({ src: resolve('./runtime/plugin'), mode: 'all' })

    addImports(['useFeatureFlag', 'useFeatureFlags', 'useUnleashContext'].map(name => ({
      name,
      from: resolve('./runtime/composables'),
    })))

    nuxt.hook('nitro:config', (nitroConfig) => {
      nitroConfig.alias = nitroConfig.alias || {}

      // Inline module runtime in Nitro bundle
      nitroConfig.externals = defu(
        typeof nitroConfig.externals === 'object' ? nitroConfig.externals : {},
        {
          inline: [resolve('./runtime')],
        },
      )
      nitroConfig.alias['#unleash'] = resolve('./runtime/server/services')
    })
    addTypeTemplate({
      filename: 'types/nuxt-unleash.d.ts',
      getContents: () =>
        [
          '// AUTO-GENERATED BY approck-nuxt-unleash',
          'declare module \'#unleash\' {',
          `  const { useUnleash }: typeof import('${resolve('./runtime/server/services')}')`,
          '}',
          '',
        ].join('\n'),
    })
  },
})

// Type inference issue when generating declaration files - module works correctly at runtime
export default moduleDefinition as unknown as ReturnType<typeof defineNuxtModule<ModuleOptions>>
